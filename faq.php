<script>
document.addEventListener('DOMContentLoaded', () => {
    const faqItems = document.querySelectorAll('.faq-item');
    const searchInput = document.getElementById('faq-search');
    const noResults = document.getElementById('faq-no-results');

    // 1. Accordion Toggle Logic
    faqItems.forEach(item => {
        const button = item.querySelector('.faq-question-btn');
        const answer = item.querySelector('.faq-answer');

        button.addEventListener('click', () => {
            const isExpanded = button.getAttribute('aria-expanded') === 'true';

            // Close all other items for a cleaner accordion effect
            faqItems.forEach(otherItem => {
                if (otherItem !== item && otherItem.classList.contains('active')) {
                    otherItem.classList.remove('active');
                    otherItem.querySelector('.faq-question-btn').setAttribute('aria-expanded', 'false');
                    otherItem.querySelector('.faq-answer').style.maxHeight = '0';
                }
            });

            // Toggle current item
            if (isExpanded) {
                item.classList.remove('active');
                button.setAttribute('aria-expanded', 'false');
                answer.style.maxHeight = '0';
            } else {
                item.classList.add('active');
                button.setAttribute('aria-expanded', 'true');
                // Set max-height dynamically to match scrollHeight for a smooth transition
                answer.style.maxHeight = answer.scrollHeight + 'px';
            }
        });
    });

    // 2. Real-time Search Filter Logic
    searchInput.addEventListener('input', (e) => {
        const searchTerm = e.target.value.toLowerCase().trim();
        let visibleCount = 0;

        faqItems.forEach(item => {
            const searchData = item.getAttribute('data-question');
            
            if (searchData.includes(searchTerm)) {
                item.style.display = 'block';
                visibleCount++;
            } else {
                item.style.display = 'none';
                // Close it if hidden
                item.classList.remove('active');
                item.querySelector('.faq-question-btn').setAttribute('aria-expanded', 'false');
                item.querySelector('.faq-answer').style.maxHeight = '0';
            }
        });

        // Toggle No Results Message
        if (visibleCount === 0) {
            noResults.style.display = 'block';
        } else {
            noResults.style.display = 'none';
        }
    });
});
</script>

